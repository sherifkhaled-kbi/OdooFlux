"""Deterministic compatibility-matrix generator (REQ-EVD-006, FR-008, FR-009).

Output depends only on the knowledge data: step research records, gaps, evidence, rule metadata,
and rule candidates. No timestamps. The generator refuses any cell that claims more than the data
supports (FR-009)."""

from odooflux.knowledge import runtime_runs
from odooflux.knowledge.loader import KnowledgeBase

VOCAB = [("NOT_ASSESSED", "No official research recorded"),
         ("RESEARCH_SEEDED", "Some official evidence records exist; the category is not fully researched"),
         ("RESEARCHED", "Every category is covered by evidence records or explicit gaps (peer-reviewed)"),
         ("RULES_DRAFTED", "Rules exist with evidence; tests incomplete"),
         ("RULES_TESTED", "Rules have passing positive/negative/idempotence tests and golden migrations"),
         ("RUNTIME_VALIDATED", "Golden migration installs and passes tests on the target version in the runtime layer")]
COLUMNS = [("Rules", "rules"), ("Python/ORM", "python_orm"), ("XML views/data", "xml_views_data"),
           ("QWeb", "qweb"), ("JS / OWL", "javascript_owl"), ("Assets", "assets"),
           ("Manifest / deps", "manifest_dependencies"), ("Security (ACL)", "security"),
           ("Runtime", "runtime"), ("Behavioural", "behavioural")]
RUN_COLUMNS = ["Runtime run record", "Behavioural verified"]
CLAIMS_TESTS = ("RULES_TESTED", "RUNTIME_VALIDATED")
RULE_CLAIM_ORDER = {"NOT_ASSESSED": 0, "RESEARCH_SEEDED": 1, "RESEARCHED": 2, "RULES_DRAFTED": 3,
                    "RULES_TESTED": 4, "RUNTIME_VALIDATED": 5}
PREAMBLE = """# Version Compatibility Matrix

GENERATED by `odooflux knowledge matrix` from `src/odooflux/knowledge/`. Do not edit by hand; run
`odooflux knowledge matrix --check` to detect drift (contracts/knowledge-cli.md).

Vocabulary is defined in [README.md](README.md#status-vocabularies):

| Value | Meaning |
|---|---|
"""
HONEST = """
**Honest status:** the data holds official evidence only. No transition is `RESEARCHED`, no rule is
`RULES_DRAFTED` under the new engine, and nothing is `RULES_TESTED` or `RUNTIME_VALIDATED`. The
legacy `odooflux.py` rules do not count: they lack evidence and tests (see
[MIGRATION_RULE_ENGINE.md](MIGRATION_RULE_ENGINE.md#legacy-rule-disposition)). No coverage
percentages are given because none were measured.
"""
EVIDENCE_NOTE = """
Evidence IDs refer to [research/OFFICIAL_EVIDENCE_REGISTER.md](research/OFFICIAL_EVIDENCE_REGISTER.md)
(EV-0xx, EV-1xx) and to [specs/004-official-source-intelligence/research.md](../../specs/004-official-source-intelligence/research.md)
(EV-2xx). Online releases are attributed to the next major (ADR-007).

"""
CATALOGUE_INTRO = """Proposed maturity is the **highest** maturity the evidence allows once tests pass; every rule
starts at `DRAFT`. "review" = flagged `review_required` (result capped at `NEEDS_REVIEW`).
Risk is the behavioural impact of a wrong transformation.

"""
TRAILER = """
`18-19.python.env-shortcuts-deprecated`: EV-209 shows the replacement for `_cr` and `_uid`. The
`_context` replacement must be located at the same SHA before the fixer is enabled (task in
feature 006).
"""


class OverclaimError(ValueError):
    """A cell or rule claims a status the data cannot support (FR-009)."""


def refuse_overclaims(kb: KnowledgeBase) -> None:
    rules_by_step = {}
    for rule in kb.rules:
        rules_by_step.setdefault(rule["step"], []).append(rule)
    for step, record in kb.research.items():
        for key, cell in record.get("categories", {}).items():
            if cell["status"] in CLAIMS_TESTS and key == "rules":
                for rule in rules_by_step.get(step, []):
                    if not rule.get("tests"):
                        raise OverclaimError(f"{step} rules: rule {rule['id']} is {cell['status']} "
                                             f"without test evidence")
        if record.get("research_status") == "RESEARCHED" and not record.get("peer_reviewed"):
            raise OverclaimError(f"{step}: RESEARCHED requires peer_reviewed")


def refuse_unbacked_runtime_claims(kb: KnowledgeBase) -> None:
    """RUNTIME_VALIDATED in research data needs a valid passing runtime run record for the step (008 T029-gen)."""
    for step, record in kb.research.items():
        claimed = [key for key, cell in record.get("categories", {}).items() if cell.get("status") == "RUNTIME_VALIDATED"]
        if claimed and runtime_runs.runtime_status(kb, step) != "RUNTIME_VALIDATED":
            raise OverclaimError(f"{step} {', '.join(sorted(claimed))}: RUNTIME_VALIDATED without a passing "
                                 f"runtime run record")


def _step_rows(kb: KnowledgeBase):
    for step in sorted(kb.research, key=lambda s: tuple(int(p) for p in s.split("-"))):
        yield step, kb.research[step]


def generate(kb: KnowledgeBase) -> str:
    refuse_overclaims(kb)
    refuse_unbacked_runtime_claims(kb)
    out = [PREAMBLE]
    out += [f"| `{v}` | {m} |\n" for v, m in VOCAB]
    out.append(HONEST)
    validated = [st for st, _ in _step_rows(kb) if runtime_runs.runtime_status(kb, st) == "RUNTIME_VALIDATED"]
    if validated:  # the HONEST text above would be wrong: say which steps have a recorded passing run
        out.append("\n**Runtime run records:** the `RUNTIME_VALIDATED` mark in the last columns comes only from a "
                   "recorded passing run in `compatibility/runtime_runs.json` (steps: "
                   + ", ".join(s.replace("-", "→") for s in validated) + "). It does not change the research or rule "
                   "statuses above.\n")
    out += ["\n## Matrix\n\n",
            "| Step | Research | " + " | ".join(name for name, _ in COLUMNS) + " | " + " | ".join(RUN_COLUMNS) + " |\n",
            "|" + "---|" * (2 + len(COLUMNS) + len(RUN_COLUMNS)) + "\n"]
    for step, record in _step_rows(kb):
        cells = [record["categories"].get(key, {}).get("status", "NOT_ASSESSED") for _, key in COLUMNS]
        out.append(f"| {step.replace('-', '→')} | {record['research_status']} | " + " | ".join(cells)
                   + f" | {runtime_runs.runtime_status(kb, step)} | {runtime_runs.behavioural_status(kb, step)} |\n")
    out.append("\nOdoo 20.0 had no official branch inspected during planning; the row is a placeholder (G-R-19).\n")
    out += ["\n## Seeded evidence per transition\n\n", EVIDENCE_NOTE,
            "| Step | Seeded evidence | Known unsupported / review-only | Open gaps |\n", "|---|---|---|---|\n"]
    for step, record in _step_rows(kb):
        evidence = record.get("seeded_evidence", [])
        gaps = record.get("open_gaps", [])
        out.append(f"| {step.replace('-', '→')} | {', '.join(evidence) or '—'} | "
                   f"{record.get('review_only', 'none recorded')} | {', '.join(gaps) or '—'} |\n")
    out += ["\n## Seed rule catalogue (candidates, not implemented)\n\n", CATALOGUE_INTRO,
            "| Rule ID | Evidence | Proposed maturity | Transformation | Risk |\n", "|---|---|---|---|---|\n"]
    for row in kb.rule_candidates:
        out.append(f"| `{row['rule_id']}` | {', '.join(row['evidence'])} | {row['proposed_maturity']} | "
                   f"{row['transformation']} | {row['risk']} |\n")
    out.append(TRAILER)
    return "".join(out)


def check_drift(kb: KnowledgeBase, committed_text: str) -> bool:
    """True when the committed file equals the generated output."""
    return generate(kb) == committed_text
