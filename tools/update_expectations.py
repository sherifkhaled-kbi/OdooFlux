#!/usr/bin/env python3
"""Regenerate PROVISIONAL expected outputs for the fixtures in tests/golden_fixtures/INDEX.json (002 T018).

For every INDEX entry whose authority is PROVISIONAL and that lists targets, run the current engine (write mode,
temporary copy, temporary state dir) and write ``expected/<target>/tree`` and ``expected/<target>/report.json`` in the
006 golden layout, plus ``input_digest`` in INDEX.json. The output is NOT approved migration truth: it only pins the
engine's present behaviour so framework mechanics can be tested (ADR-019). Changes need human review (FHR-A-002).

Refuses to run when ``git status --porcelain tests/golden_fixtures`` is non-empty unless ``--force``.
Run from the repository root:  PYTHONPATH=src python3 tools/update_expectations.py [--force]
"""

import argparse
import json
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "src"))

from tests._support import fixtures  # noqa: E402
from tests._support.digest import digest_hex  # noqa: E402
from tests.integration.test_golden_migrations import GoldenCase, run_case  # noqa: E402

MARKER = ("# PROVISIONAL\n\nGenerated by `tools/update_expectations.py` from the current engine. Not approved migration "
          "truth; not independently reviewed. Certification: PENDING_HUMAN_REVIEW (FHR-A-002).\n")


def _dirty() -> bool:
    out = subprocess.run(["git", "status", "--porcelain", "tests/golden_fixtures"], cwd=ROOT,
                         stdout=subprocess.PIPE, text=True).stdout
    return bool(out.strip())


def _write(path: Path, data: bytes, changed: list) -> None:
    if not path.exists() or path.read_bytes() != data:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
        changed.append(str(path.relative_to(ROOT)))


def regenerate(changed: list) -> None:
    index_path = fixtures.INDEX_PATH
    data = json.loads(index_path.read_text(encoding="utf-8"))
    for item in data["fixtures"]:
        item["input_digest"] = fixtures.input_digest(item)
        if item.get("authority") != "PROVISIONAL" or not item.get("targets"):
            continue
        module = fixtures.module_dir(item)
        for target in item["targets"]:
            case = GoldenCase(item["source_version"], target, module, module / "expected" / target)
            with tempfile.TemporaryDirectory() as tmp:
                report, migrated = run_case(case, Path(tmp))
                dest = module / "expected" / target
                existing = dest / "tree"
                if not existing.exists() or digest_hex(existing) != digest_hex(migrated):
                    shutil.rmtree(existing, ignore_errors=True)
                    shutil.copytree(migrated, existing)
                    changed.append(str(existing.relative_to(ROOT)) + "/")
                _write(dest / "report.json",
                       (json.dumps(report, indent=2, sort_keys=True) + "\n").encode("utf-8"), changed)
                _write(dest / "PROVISIONAL.md", MARKER.encode("utf-8"), changed)
        _write(module / "expected" / "PROVISIONAL.md", MARKER.encode("utf-8"), changed)
    _write(index_path, (json.dumps(data, indent=2) + "\n").encode("utf-8"), changed)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--force", action="store_true", help="run even when tests/golden_fixtures has uncommitted changes")
    args = parser.parse_args(argv)
    if _dirty() and not args.force:
        print("refusing: tests/golden_fixtures has uncommitted changes (use --force)", file=sys.stderr)
        return 2
    changed: list = []
    regenerate(changed)
    print("\n".join(sorted(set(changed))) or "no changes")
    return 0


if __name__ == "__main__":
    sys.exit(main())
