"""RC performance fix: rename pairing must not score every removed subject against every added one.

A real Odoo pair has ~20k removed and ~20k added subjects of one kind; the all-pairs scan made 460 million
`score` calls. Candidates are now generated by an exact filter (a pair scoring at or above the threshold must share
a body digest and enough attribute items); the final decision still comes from `score`, so results are unchanged.
"""

import itertools
import random
import unittest
from unittest import mock

from odooflux.knowledge.extract import classify as c
from odooflux.knowledge.extract import rename as r
from tests.unit.knowledge.kap.test_rename import FROM, TO, _fact


def facts(prefix, n, rng, shared_body=False):
    out = []
    for i in range(n):
        attrs = {"type": rng.choice(["Char", "Integer", "Many2one"]), "size": rng.randint(1, 6),
                 "tag": f"t{rng.randint(1, 4)}", "unique": f"{prefix}{i}"}
        out.append(_fact(f"addons/a/m{i % 7}.py", f"res.x::field::{prefix}{i}", attrs=attrs,
                         body=None if shared_body else f"d{prefix}{i}"))
    return out


def _keys(drafts, facts_, cls):
    by = {(f["domain"], f["kind"], f["subject_key"]): f for f in facts_}
    return {sid: r._class_key(sid, by[sid]) for d in drafts if d["class"] == cls
            for sid in [(d["domain"], d["kind"], d["subject_key"])]}


def run(before, after, config=None):
    drafts = c.classify_pair(before, after, from_snapshot_id=FROM, to_snapshot_id=TO, config=config)
    return r.refine_candidates(drafts, before, after, config=config)


def reference(drafts, before, after, threshold):
    """The original all-pairs candidate relation."""
    by_b = {(f["domain"], f["kind"], f["subject_key"]): f for f in before}
    by_a = {(f["domain"], f["kind"], f["subject_key"]): f for f in after}
    removed = [(d["domain"], d["kind"], d["subject_key"]) for d in drafts if d["class"] == "REMOVED"]
    added = [(d["domain"], d["kind"], d["subject_key"]) for d in drafts if d["class"] == "ADDED"]
    return {(a, b) for a in removed for b in added if a[:2] == b[:2] and r.score(by_b[a], by_a[b]) >= threshold}


class ScaleTests(unittest.TestCase):
    def test_score_calls_are_far_below_all_pairs(self):
        rng = random.Random(7)
        before, after = facts("o", 400, rng), facts("n", 400, rng)
        with mock.patch.object(r, "score", wraps=r.score) as spy:
            run(before, after)
        self.assertLess(spy.call_count, 400 * 400 // 20)

    def test_candidate_set_equals_the_all_pairs_relation(self):
        rng = random.Random(11)
        for shared in (False, True):
            before, after = facts("o", 60, rng, shared), facts("n", 60, rng, shared)
            # make some genuine renames: same attrs and body under a new name
            for i in range(0, 60, 6):
                after[i] = dict(before[i], subject_key=f"res.x::field::renamed{i}")
            config = c.load_config()
            drafts = c.classify_pair(before, after, from_snapshot_id=FROM, to_snapshot_id=TO, config=config)
            rk, ak = _keys(drafts, before, "REMOVED"), _keys(drafts, after, "ADDED")
            got = set(r._candidate_pairs(list(set(rk.values())), list(set(ak.values())),
                                         float(config["rename_threshold"])))
            expected = {(rk[a], ak[b]) for a, b in reference(drafts, before, after, float(config["rename_threshold"]))}
            self.assertTrue(expected <= got, "a qualifying pair was filtered out")

    def test_low_threshold_still_finds_every_pair(self):
        rng = random.Random(3)
        before, after = facts("o", 30, rng), facts("n", 30, rng)
        config = dict(c.load_config(), rename_threshold=0.3)
        drafts = c.classify_pair(before, after, from_snapshot_id=FROM, to_snapshot_id=TO, config=config)
        rk, ak = _keys(drafts, before, "REMOVED"), _keys(drafts, after, "ADDED")
        got = set(r._candidate_pairs(list(set(rk.values())), list(set(ak.values())), 0.3))
        self.assertTrue({(rk[a], ak[b]) for a, b in reference(drafts, before, after, 0.3)} <= got)


class IdenticalAttributeScaleTests(unittest.TestCase):
    """Real trees hold thousands of subjects with identical attributes and no body (plain fields). Every pair of them
    qualifies, so the candidate relation is quadratic: it is evaluated per attribute class, never per pair, and an
    ambiguous subject lists at most MAX_CANDIDATES candidates plus their total."""

    def mk(self, prefix, n):
        return [_fact(f"a/m{i % 9}.py", f"res.x::field::{prefix}{i}", attrs={"type": "Char"}, body=None)
                for i in range(n)]

    def test_thousands_of_identical_subjects_finish_fast_and_stay_bounded(self):
        import time
        before, after = self.mk("o", 3000), self.mk("n", 3000)
        started = time.time()
        out = run(before, after)
        self.assertLess(time.time() - started, 10)
        unknown = [d for d in out if d["class"] == "UNKNOWN"]
        self.assertEqual(len(unknown), 6000)
        for d in unknown:
            self.assertLessEqual(len(d["detail"]["candidates"]), r.MAX_CANDIDATES)
            self.assertEqual(d["detail"]["candidate_count"], 3000)
            self.assertLessEqual(len(d["locations"]), 1 + r.MAX_CANDIDATES * 2)

    def test_listed_candidates_are_the_smallest_names_and_deterministic(self):
        before, after = self.mk("o", 40), self.mk("n", 40)
        a = run(before, after)
        b = run(list(reversed(before)), list(reversed(after)))
        self.assertEqual(a, b)
        d = next(x for x in a if x["subject_key"] == "res.x::field::o7")
        names = d["detail"]["candidates"]
        self.assertEqual(names, sorted(names))
        self.assertEqual(names, sorted(f"res.x::field::n{i}" for i in range(40))[:r.MAX_CANDIDATES])

    def test_capped_ambiguity_stays_unknown_and_is_never_provable(self):
        from odooflux.knowledge.extract import proofs
        out = run(self.mk("o", 30), self.mk("n", 30))
        capped = [d for d in out if d["detail"].get("candidate_count")]
        self.assertEqual(len(capped), 60)
        for d in capped:
            self.assertEqual((d["class"], d.get("confirmed", False)), ("UNKNOWN", False))
        refusal = proofs.prove(ledger_class="UNKNOWN", old="a", new="b", from_path="odoo/x.py", to_path="odoo/x.py",
                               from_text="", to_text="")
        self.assertEqual(refusal.code, "UNSUPPORTED_CLASS")  # UNKNOWN never reaches an automatic fix

    def test_small_ambiguity_is_listed_in_full_without_a_count(self):
        before, after = self.mk("o", 1), self.mk("n", 3)
        d = next(x for x in run(before, after) if x["subject_key"].endswith("::o0"))
        self.assertEqual(len(d["detail"]["candidates"]), 3)
        self.assertNotIn("candidate_count", d["detail"])


class ThresholdBoundaryTests(unittest.TestCase):
    """Threshold 0.8 needs identical bodies and a jaccard of at least 0.6 (3 of 5 items)."""

    def pair(self, old_attrs, new_attrs, body="b"):
        before = [_fact("a/x.py", "res.x::field::old", attrs=old_attrs, body=body)]
        after = [_fact("a/x.py", "res.x::field::new", attrs=new_attrs, body=body)]
        return run(before, after)

    def test_exact_boundary_jaccard_is_a_rename(self):
        out = self.pair({"a": 1, "b": 1, "c": 1, "d": 1}, {"a": 1, "b": 1, "c": 1, "e": 1})  # 3/5 = 0.6
        self.assertIn("RENAMED_CANDIDATE", [d["class"] for d in out])

    def test_just_below_the_boundary_is_not(self):
        out = self.pair({"a": 1, "b": 1, "c": 1, "d": 1, "e": 1}, {"a": 1, "b": 1, "c": 1, "f": 1, "g": 1})  # 3/7
        self.assertNotIn("RENAMED_CANDIDATE", [d["class"] for d in out])

    def test_different_body_never_renames_at_this_threshold(self):
        before = [_fact("a/x.py", "res.x::field::old", attrs={"a": 1}, body="b1")]
        after = [_fact("a/x.py", "res.x::field::new", attrs={"a": 1}, body="b2")]
        self.assertNotIn("RENAMED_CANDIDATE", [d["class"] for d in run(before, after)])


if __name__ == "__main__":
    unittest.main()
