"""TST-002-011 (REQ-TST-002): report-only legacy rule coverage.

Legacy rule categories are read from the rule tables in ``src/odooflux/rules/shared/legacy_rules.py`` with ``ast``
(the module is not imported). Tests tag coverage in docstrings as ``rule:<category>:<kind>`` where kind is
``positive``, ``negative`` or ``idempotence``. The report is written to ``tests/rule_coverage.txt``. It never fails on
missing coverage (enforcement is deferred to P5, 006).

Note: the original task named ``odooflux.py``; the rule tables moved to the package in the P2 cut-over (003).
"""

import ast
import re
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TABLES = ROOT / "src" / "odooflux" / "rules" / "shared" / "legacy_rules.py"
REPORT = ROOT / "tests" / "rule_coverage.txt"
KINDS = ("positive", "negative", "idempotence")
_TABLE_NAMES = {"PYTHON_RULES", "XML_RULES", "MANIFEST_RULES", "JS_TS_RULES", "CSS_RULES"}
_TAG = re.compile(r"rule:([A-Za-z0-9 ()_.\-]+?):(positive|negative|idempotence)")


def legacy_categories(path: Path = TABLES) -> dict:
    """{table name: sorted categories} read from the assignments, without importing the module."""
    tree = ast.parse(path.read_text(encoding="utf-8"))
    result = {}
    for node in tree.body:
        if isinstance(node, ast.Assign) and isinstance(node.value, ast.List):
            names = [t.id for t in node.targets if isinstance(t, ast.Name)]
            if names and names[0] in _TABLE_NAMES:
                cats = set()
                for elt in node.value.elts:
                    if isinstance(elt, ast.Tuple) and len(elt.elts) > 4 and isinstance(elt.elts[4], ast.Constant):
                        cats.add(elt.elts[4].value)
                result[names[0]] = sorted(cats)
    return result


def tagged_coverage(tests_root: Path = ROOT / "tests") -> dict:
    """{category: set of kinds} gathered from docstrings of test functions and classes."""
    found = {}
    for file in sorted(tests_root.rglob("test_*.py")):
        try:
            tree = ast.parse(file.read_text(encoding="utf-8"))
        except SyntaxError:
            continue
        for node in ast.walk(tree):
            if isinstance(node, (ast.Module, ast.ClassDef, ast.FunctionDef)):
                for m in _TAG.finditer(ast.get_docstring(node) or ""):
                    found.setdefault(m.group(1), set()).add(m.group(2))
    return found


def render(categories: dict, coverage: dict) -> str:
    lines = ["# Legacy rule coverage (report only; generated by tests/unit/test_rule_coverage_report.py)",
             "# category | positive | negative | idempotence", ""]
    for table in sorted(categories):
        lines.append(f"[{table}]")
        for cat in categories[table]:
            kinds = coverage.get(cat, set())
            lines.append(f"{cat} | " + " | ".join("yes" if k in kinds else "-" for k in KINDS))
        lines.append("")
    return "\n".join(lines)


class RuleCoverageReportTests(unittest.TestCase):
    def test_report_lists_every_category_with_three_columns(self):
        categories = legacy_categories()
        self.assertTrue(categories.get("PYTHON_RULES"))
        self.assertTrue(categories.get("XML_RULES"))
        text = render(categories, tagged_coverage())
        REPORT.write_text(text, encoding="utf-8")
        for cats in categories.values():
            for cat in cats:
                row = next(line for line in text.splitlines() if line.startswith(f"{cat} | "))
                self.assertEqual(row.count("|"), 3)

    def test_tag_parsing(self):
        self.assertEqual({m.group(2) for m in _TAG.finditer("rule:Tree Tag Renamed:positive rule:X:idempotence")},
                         {"positive", "idempotence"})

    def test_render_marks_presence(self):
        out = render({"T": ["A", "B"]}, {"A": {"positive"}})
        self.assertIn("A | yes | - | -", out)
        self.assertIn("B | - | - | -", out)


if __name__ == "__main__":
    unittest.main()
